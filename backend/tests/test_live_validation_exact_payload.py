import os
import sys
import uuid
import requests
from datetime import datetime, timezone, timedelta

# Ensure backend and backend/db path is in sys.path
backend_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, backend_dir)
sys.path.insert(0, os.path.join(backend_dir, "db"))

from db.database import SessionLocal
from models import HistoricalOrder, Customer, AuditLog, User
from auth_utils import create_access_token, register_user_session

API_BASE = "http://127.0.0.1:8000"

def run_test():
    print("=" * 60)
    print("RUNNING LIVE HTTP INTEGRATION TEST WITH EXACT BROWSER PAYLOAD")
    print("=" * 60)

    db = SessionLocal()
    admin_user = db.query(User).filter(User.username == "admin").first()
    if not admin_user:
        print("ERROR: Admin user not found in database!")
        db.close()
        sys.exit(1)

    sid = str(uuid.uuid4())
    token = create_access_token(
        data={"sub": admin_user.username, "role": "admin", "uid": admin_user.user_id},
        session_id=sid
    )
    register_user_session(db, admin_user, sid)
    db.commit()

    headers = {
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json"
    }

    # Step 1: Verify baseline state of Candidate 1 (1507)
    order_1507 = db.query(HistoricalOrder).filter(HistoricalOrder.historical_order_id == 1507).first()
    if not order_1507:
        print("ERROR: Order 1507 not found!")
        db.close()
        sys.exit(1)

    orig_status = order_1507.ocr_status
    orig_target_prov = order_1507.target_provenance
    orig_comp_days = order_1507.completion_days
    orig_sync = order_1507.sync_status
    orig_cust_id = order_1507.customer_id
    orig_cust_name = order_1507.customer.customer_name if order_1507.customer else None
    orig_cust_contact = order_1507.customer.contact_number if order_1507.customer else None

    print(f"[BASELINE] Candidate 1507 status={orig_status}, completion_days={orig_comp_days}, customer={orig_cust_name}")

    # Track audit logs before test
    audit_ids_before = set(r[0] for r in db.query(AuditLog.audit_log_id).filter(AuditLog.record_id == 1507).all())

    # Step 2: Test Exact Browser Payload on ACCEPT
    # Exact payload generated by HistoricalValidationQueue.tsx:
    exact_browser_accept_payload = {
        "action": "approve",
        "was_corrected": False
    }

    print(f"\n[TEST 1] Sending exact browser ACCEPT payload to {API_BASE}/api/historical/processing/validate-order/1507:")
    print(f"Payload: {exact_browser_accept_payload}")

    resp = requests.post(
        f"{API_BASE}/api/historical/processing/validate-order/1507",
        json=exact_browser_accept_payload,
        headers=headers,
        timeout=10
    )

    print(f"Response status: {resp.status_code}")
    print(f"Response body: {resp.text}")

    if resp.status_code != 200:
        print(f"FAILURE: Expected 200, got {resp.status_code}")
        db.close()
        sys.exit(1)

    data = resp.json()
    assert data.get("status") == "success", "Response status != success"
    assert data.get("new_status") == "VALIDATED", f"Expected VALIDATED, got {data.get('new_status')}"
    assert data.get("is_ml_eligible") is True, f"Expected is_ml_eligible=True, got {data.get('is_ml_eligible')}"
    assert data.get("completion_days") == 4, f"Expected completion_days=4, got {data.get('completion_days')}"
    print(">>> HTTP ACCEPT test: PASSED")

    # Verify in DB
    db.expire_all()
    check_order = db.query(HistoricalOrder).filter(HistoricalOrder.historical_order_id == 1507).first()
    assert check_order.ocr_status == "VALIDATED", f"DB ocr_status != VALIDATED, got {check_order.ocr_status}"
    assert check_order.completion_days == 4, f"DB completion_days != 4, got {check_order.completion_days}"
    assert check_order.target_provenance == "CLAIM_DATE_CALCULATED", f"DB target_provenance != CLAIM_DATE_CALCULATED, got {check_order.target_provenance}"
    assert check_order.sync_status == "CONFIRMED_ML_ELIGIBLE", f"DB sync_status != CONFIRMED_ML_ELIGIBLE, got {check_order.sync_status}"
    print(">>> DB state verification after ACCEPT: PASSED")

    # Step 3: Test EDIT Relationship Handling (genuine correction with customer dictionary)
    print("\n[TEST 2] Testing EDIT workflow with customer dict correction:")
    edit_payload = {
        "action": "save",
        "was_corrected": True,
        "corrections": {
            "customer": {
                "name": "Edited Name Test",
                "contact": "09998887777"
            },
            "control_no": "TEST-CTRL-123"
        }
    }
    resp_edit = requests.post(
        f"{API_BASE}/api/historical/processing/validate-order/1507",
        json=edit_payload,
        headers=headers,
        timeout=10
    )
    print(f"Edit Response status: {resp_edit.status_code}")
    print(f"Edit Response body: {resp_edit.text}")
    assert resp_edit.status_code == 200, f"Edit response status != 200, got {resp_edit.status_code}"

    db.expire_all()
    check_edit = db.query(HistoricalOrder).filter(HistoricalOrder.historical_order_id == 1507).first()
    assert check_edit.customer.customer_name == "Edited Name Test", f"Customer name was not updated"
    assert check_edit.customer.contact_number == "09998887777", f"Customer contact was not updated"
    print(">>> EDIT relationship handling: PASSED")

    # Step 4: Test REJECT workflow
    print("\n[TEST 3] Testing REJECT workflow:")
    reject_payload = {
        "action": "reject",
        "reason": "Test Rejection Verification"
    }
    resp_reject = requests.post(
        f"{API_BASE}/api/historical/processing/validate-order/1507",
        json=reject_payload,
        headers=headers,
        timeout=10
    )
    print(f"Reject Response status: {resp_reject.status_code}")
    assert resp_reject.status_code == 200, f"Reject response status != 200, got {resp_reject.status_code}"
    db.expire_all()
    check_reject = db.query(HistoricalOrder).filter(HistoricalOrder.historical_order_id == 1507).first()
    assert check_reject.ocr_status == "REJECTED", f"Expected REJECTED, got {check_reject.ocr_status}"
    print(">>> REJECT workflow: PASSED")

    # Step 5: Clean Rollback / Restore to Baseline
    print("\n[ROLLBACK] Restoring Candidate 1507 and cleaning test audit logs...")
    check_order = db.query(HistoricalOrder).filter(HistoricalOrder.historical_order_id == 1507).first()
    check_order.ocr_status = orig_status
    check_order.completion_days = orig_comp_days
    check_order.target_provenance = orig_target_prov
    check_order.sync_status = orig_sync
    check_order.validated_by = None
    check_order.validated_at = None
    if check_order.customer:
        check_order.customer.customer_name = orig_cust_name
        check_order.customer.contact_number = orig_cust_contact

    # Remove any test audit logs created during this run
    audit_ids_after = set(r[0] for r in db.query(AuditLog.audit_log_id).filter(AuditLog.record_id == 1507).all())
    new_audit_ids = audit_ids_after - audit_ids_before
    if new_audit_ids:
        db.query(AuditLog).filter(AuditLog.audit_log_id.in_(new_audit_ids)).delete(synchronize_session=False)

    db.commit()
    print(">>> Candidate 1507 successfully rolled back to PENDING_REVIEW.")

    # Step 6: Full Database Baseline Count Verification
    active_count = db.query(HistoricalOrder).filter(HistoricalOrder.is_legacy_archived == False).count()
    pending_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.ocr_status.in_(["PENDING_REVIEW", "UNPROCESSED"])
    ).count()
    potential_ml_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.potential_ml_candidate == True,
        HistoricalOrder.ocr_status == "PENDING_REVIEW"
    ).count()
    validated_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.ocr_status == "VALIDATED"
    ).count()
    corrected_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.ocr_status == "CORRECTED"
    ).count()
    rejected_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.ocr_status == "REJECTED"
    ).count()
    confirmed_ml_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.sync_status == "CONFIRMED_ML_ELIGIBLE"
    ).count()
    clean_ml_count = db.query(HistoricalOrder).filter(
        HistoricalOrder.is_legacy_archived == False,
        HistoricalOrder.ocr_status.in_(["VALIDATED", "CORRECTED"]),
        HistoricalOrder.completion_days.isnot(None),
        HistoricalOrder.target_provenance == "CLAIM_DATE_CALCULATED"
    ).count()

    print("\n" + "=" * 60)
    print("FINAL DATABASE BASELINE VERIFICATION:")
    print(f"Active CSV:             {active_count} (Expected: 714)")
    print(f"Pending:                {pending_count} (Expected: 714)")
    print(f"Potential ML Remaining: {potential_ml_count} (Expected: 120)")
    print(f"Validated:              {validated_count} (Expected: 0)")
    print(f"Corrected:              {corrected_count} (Expected: 0)")
    print(f"Rejected:               {rejected_count} (Expected: 0)")
    print(f"Confirmed ML Eligible:  {confirmed_ml_count} (Expected: 0)")
    print(f"Clean ML Dataset:       {clean_ml_count} (Expected: 0)")
    print(f"Candidate 1507 status:  {check_order.ocr_status} (Expected: PENDING_REVIEW)")
    print("=" * 60)

    assert active_count == 714, f"Active count != 714: {active_count}"
    assert pending_count == 714, f"Pending count != 714: {pending_count}"
    assert potential_ml_count == 120, f"Potential ML != 120: {potential_ml_count}"
    assert validated_count == 0, f"Validated != 0: {validated_count}"
    assert corrected_count == 0, f"Corrected != 0: {corrected_count}"
    assert rejected_count == 0, f"Rejected != 0: {rejected_count}"
    assert confirmed_ml_count == 0, f"Confirmed ML != 0: {confirmed_ml_count}"
    assert clean_ml_count == 0, f"Clean ML != 0: {clean_ml_count}"
    assert check_order.ocr_status == "PENDING_REVIEW", f"Order 1507 status != PENDING_REVIEW"

    db.close()
    print("\nALL VERIFICATIONS PASSED PERFECTLY!")

if __name__ == "__main__":
    run_test()
